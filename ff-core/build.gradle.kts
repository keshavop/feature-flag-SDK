// Exposes the build version to code (User-Agent, diagnostic events) without a runtime lookup.
val generateSdkVersion =
    tasks.register("generateSdkVersion") {
        val version = providers.gradleProperty("VERSION_NAME")
        val outputDir = layout.buildDirectory.dir("generated/sdkVersion/commonMain/kotlin")
        inputs.property("version", version)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().file("io/github/keshavop/featureflags/core/SdkVersion.kt").asFile
            file.parentFile.mkdirs()
            file.writeText(
                """
            |// Generated by :ff-core:generateSdkVersion. Do not edit.
            |package io.github.keshavop.featureflags.core
            |
            |internal const val SDK_VERSION: String = "${version.get()}"
            |
                """.trimMargin(),
            )
        }
    }

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateSdkVersion)
            dependencies {
                api(libs.kotlinx.serialization.json)
            }
        }
    }
}

// Embeds the shared conformance vectors (conformance/*.json) into commonTest so every target — JVM, JS and iOS —
// runs exactly the same cases without platform file access.
val generateConformanceSources =
    tasks.register("generateConformanceSources") {
        val sourceDir = rootProject.layout.projectDirectory.dir("conformance")
        val outputDir = layout.buildDirectory.dir("generated/conformance/commonTest/kotlin")
        inputs.files(fileTree(sourceDir) { include("**/*.json") }).withPropertyName("vectors")
        outputs.dir(outputDir)
        doLast {
            val root = sourceDir.asFile
            val files =
                root
                    .walkTopDown()
                    .filter { it.isFile && it.extension == "json" }
                    .sortedBy { it.relativeTo(root).path }
                    .toList()
            val entries =
                files.joinToString(",\n") { file ->
                    // JVM string constants are limited to 64 KB, so long files are split into chunks
                    val chunks =
                        file
                            .readText()
                            .chunked(16_000)
                            .joinToString(" +\n        ") { "\"\"\"" + it.replace("$", "\${'$'}") + "\"\"\"" }
                    "    \"${file.relativeTo(root).invariantSeparatorsPath}\" to\n        $chunks"
                }
            val target = outputDir.get().file("io/github/keshavop/featureflags/core/ConformanceFiles.kt").asFile
            target.parentFile.mkdirs()
            target.writeText(
                "// Generated by :ff-core:generateConformanceSources from conformance/. Do not edit.\n" +
                    "package io.github.keshavop.featureflags.core\n\n" +
                    "internal val CONFORMANCE_FILES: Map<String, String> =\n    mapOf(\n$entries,\n    )\n",
            )
        }
    }

kotlin.sourceSets.commonTest {
    kotlin.srcDir(generateConformanceSources)
}

kotlin.sourceSets.named("jvmTest") {
    dependencies {
        implementation(libs.lincheck)
    }
}

