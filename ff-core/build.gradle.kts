plugins {
    id("ff.kmp-library")
    id("ff.maven-publish")
}

// Exposes the build version to code (User-Agent, diagnostic events) without a runtime lookup.
val generateSdkVersion =
    tasks.register("generateSdkVersion") {
        val version = providers.gradleProperty("VERSION_NAME")
        val outputDir = layout.buildDirectory.dir("generated/sdkVersion/commonMain/kotlin")
        inputs.property("version", version)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().file("io/github/keshavop/featureflags/core/SdkVersion.kt").asFile
            file.parentFile.mkdirs()
            file.writeText(
                """
            |// Generated by :ff-core:generateSdkVersion. Do not edit.
            |package io.github.keshavop.featureflags.core
            |
            |internal const val SDK_VERSION: String = "${version.get()}"
            |
                """.trimMargin(),
            )
        }
    }

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateSdkVersion)
        }
    }
}
